-- 6a. Citire publică anonimă — doar tabelele citite efectiv cu cheia anon.
--     `gallery` (momente-cu-mirii.astro) și `track_plays` (TrackPlaysBadge.astro)
--     se citesc la build prin getSupabasePublic(). `video_views` NU primește
--     politică: este citit exclusiv de /api/views/, cu service_role.
drop policy if exists "public read posts"       on public.posts;
drop policy if exists "public read comments"    on public.comments;
drop policy if exists "public read gallery"     on public.gallery;
drop policy if exists "public read track_plays" on public.track_plays;
drop policy if exists "public read video_views" on public.video_views;

create policy "public read posts"       on public.posts       for select to anon, authenticated using (true);
create policy "public read comments"    on public.comments    for select to anon, authenticated using (true);
create policy "public read gallery"     on public.gallery     for select to anon, authenticated using (true);
create policy "public read track_plays" on public.track_plays for select to anon, authenticated using (true);

-- 6b. Tabelele private NU primesc nicio politică.
--     Cu RLS activ și zero politici, `anon` și `authenticated` nu pot citi sau
--     scrie nimic. `service_role` ocolește RLS prin definiție — endpoint-urile
--     server-side trebuie să folosească SUPABASE_SERVICE_ROLE_KEY.
--     Tabele vizate: rezervari, budget_intents, couple_submissions,
--     gdpr_consimtamant. Scrierile în gallery/comments se fac tot cu service_role.

-- ───────────────────────────────────────────────────────────────────────────
-- 7. PERMISIUNI PE FUNCȚII
--    Funcțiile sunt SECURITY DEFINER: fără REVOKE, oricine cu cheia anon
--    le-ar putea apela. Browserul NU apelează niciodată direct aceste RPC-uri;
--    trece prin /api/views/ și /api/track-plays/, care folosesc service_role
--    și aplică rate limiting. Deci anon nu primește EXECUTE pe nimic —
--    altfel contoarele ar putea fi umflate direct, ocolind limitarea.
-- ───────────────────────────────────────────────────────────────────────────

revoke all on function public.increment_track_play(varchar)  from public, anon, authenticated;
revoke all on function public.increment_video_view(varchar)  from public, anon, authenticated;
revoke all on function public.log_gdpr_consent(varchar, varchar, text, varchar, varchar, varchar) from public, anon, authenticated;
revoke all on function public.purge_old_budget_intents()     from public, anon, authenticated;
revoke all on function public.purge_old_gdpr_consents()      from public, anon, authenticated;

grant execute on function public.increment_track_play(varchar) to service_role;
grant execute on function public.increment_video_view(varchar) to service_role;
grant execute on function public.log_gdpr_consent(varchar, varchar, text, varchar, varchar, varchar) to service_role;
grant execute on function public.purge_old_budget_intents() to service_role;
grant execute on function public.purge_old_gdpr_consents()  to service_role;

