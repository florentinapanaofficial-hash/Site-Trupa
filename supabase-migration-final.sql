-- ───────────────────────────────────────────────────────────────────────────
-- 5. FUNCȚII RPC — înlocuiesc construcțiile MySQL fără echivalent în PostgREST
--
--    PostgREST nu are tranzacții multi-request. Fiecare funcție de mai jos
--    este atomică prin natura unui singur statement INSERT ... ON CONFLICT,
--    înlocuind `ON DUPLICATE KEY UPDATE` + BEGIN/COMMIT din `api/views.ts`.
-- ───────────────────────────────────────────────────────────────────────────

create or replace function public.increment_track_play(p_track_id varchar)
returns integer
language sql
security definer
set search_path = public
as $$
  insert into public.track_plays (track_id, play_count, updated_at)
  values (p_track_id, 1, now())
  on conflict (track_id)
  do update set play_count = public.track_plays.play_count + 1, updated_at = now()
  returning play_count;
$$;

create or replace function public.increment_video_view(p_video_id varchar)
returns integer
language sql
security definer
set search_path = public
as $$
  insert into public.video_views (video_id, views_count, updated_at)
  values (p_video_id, 1, now())
  on conflict (video_id)
  do update set views_count = public.video_views.views_count + 1, updated_at = now()
  returning views_count;
$$;

-- Înlocuiește `SHA2(?, 256)` din MySQL: IP-ul brut este hașat în interiorul
-- bazei de date, deci nu ajunge niciodată stocat în clar.
create or replace function public.log_gdpr_consent(
  p_tip        varchar,
  p_canal      varchar,
  p_ip         text,
  p_user_agent varchar default null,
  p_referer    varchar default null,
  p_versiune   varchar default '1.0'
)
returns bigint
language sql
security definer
set search_path = public
as $$
  insert into public.gdpr_consimtamant
    (tip_consimtamant, canal, ip_hash, user_agent, referer, versiune_politica)
  values
    (p_tip, p_canal, encode(digest(p_ip, 'sha256'), 'hex'), p_user_agent, p_referer, p_versiune)
  returning id;
$$;

-- Echivalentul MySQL `DELETE ... WHERE selected_at < NOW() - INTERVAL 12 MONTH`.
create or replace function public.purge_old_budget_intents()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted integer;
begin
  delete from public.budget_intents where selected_at < now() - interval '12 months';
  get diagnostics deleted = row_count;
  return deleted;
end;
$$;

-- Retenție GDPR 12 luni (vezi gdpr/POLITICA-RETENTIE.md). În MySQL rula prin
-- Event Scheduler; în Supabase se programează cu pg_cron după activarea extensiei.
create or replace function public.purge_old_gdpr_consents()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted integer;
begin
  delete from public.gdpr_consimtamant where data_consimtamant < now() - interval '12 months';
  get diagnostics deleted = row_count;
  return deleted;
end;
$$;

